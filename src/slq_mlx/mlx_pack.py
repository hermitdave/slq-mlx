"""Pack an SLQ store into MLX's native quantized format.

``nn.QuantizedLinear.__call__`` runs ``mx.quantized_matmul``, which dequantizes
inside the GEMM kernel. A checkpoint built from this module therefore stays
packed in *memory* as well as on disk -- the property that makes the SLQ
bitwidth actually mean something at export time.

Two supported shapes of output:

``packed`` (default)
    The integer grid is bit-packed into uint32 and the decoder ``Linear`` layers
    are replaced by ``nn.QuantizedLinear``. mlx-lm loads it through the standard
    custom-architecture path (``config.json`` -> ``model_file`` plus
    ``trust_remote_code=True``). This is the artifact that honours the SLQ
    bitwidth.

``dequantized``
    Fake-quantized weights written as float16. Always BF16-sized regardless of
    the SLQ bitwidth, so it is useful only for debugging or as a fallback when
    a runtime without a quantized GEMM is the target.
"""

import json
import logging
import os
import shutil
import sys
from pathlib import Path

import mlx.core as mx
import mlx.nn as nn
import numpy as np
from safetensors import safe_open
from safetensors.mlx import save_file

from .mlx_weight_store import WeightStore

logging.basicConfig(level=logging.INFO, format="%(asctime)s - %(levelname)s - %(message)s")
logger = logging.getLogger(__name__)

# mx.quantize affine mode only accepts these; anything else rounds up.
SUPPORTED_BITS = (2, 3, 4, 5, 6, 8)
SUPPORTED_GROUP_SIZES = (32, 64, 128)


def _sanitize_model_name(model_id: str) -> str:
    """Strip precision suffixes from a local model directory name.

    A user may point ``--model`` at a local BF16/FP16 checkpoint directory
    (e.g. ``Spark-X2.6-4B-BF16``).  We do not want the packed quantized
    checkpoint to inherit that suffix, because it implies the artifact is
    still full-precision.  Strip common precision markers so the output
    directory name clearly identifies the artifact as a quantized checkpoint.
    """
    name = Path(model_id).name
    for suffix in ("-BF16", "-bf16", "-FP16", "-fp16", "-F16", "-f16"):
        if name.endswith(suffix):
            name = name[: -len(suffix)]
            break
    return name


def pack_row(values: np.ndarray, bits: int) -> np.ndarray:
    """Pack one row of unsigned ints into uint32, LSB-first.

    Matches ``mx.quantize(..., mode="affine")`` exactly: value ``i`` bit ``j``
    lands at bit position ``i * bits + j`` of the concatenated stream, and the
    stream is packed little-endian into uint32 words.

    Verified against ``mx.quantize`` for bits 2/3/4/5/6/8.
    """
    values = np.asarray(values).astype(np.uint64)
    shifts = np.arange(bits, dtype=np.uint64)
    # bits_set[i, j] = bit j of value i; reshaping row-major yields exactly the
    # target stream order (position i*bits + j).
    bits_set = ((values[:, None] >> shifts[None, :]) & 1).astype(np.uint8)
    stream = bits_set.reshape(-1)

    pad = (-stream.size) % 8
    if pad:
        stream = np.concatenate([stream, np.zeros(pad, dtype=np.uint8)])
    packed = np.packbits(stream.reshape(-1, 8), axis=1, bitorder="little").reshape(-1)

    pad = (-packed.size) % 4
    if pad:
        packed = np.concatenate([packed, np.zeros(pad, dtype=np.uint8)])
    return packed.reshape(-1, 4).copy().view(np.uint32).reshape(-1)


def pack_weight(values: np.ndarray, bits: int) -> np.ndarray:
    """Pack a 2-D weight row by row, matching ``mx.quantize``'s layout."""
    return np.stack([pack_row(row, bits) for row in np.asarray(values)])


def effective_bits(bits: int) -> int:
    """Round a requested bitwidth to the nearest supported one (upwards)."""
    for b in SUPPORTED_BITS:
        if b >= bits:
            return b
    return 8


