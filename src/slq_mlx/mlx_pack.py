# ``{model_module}`` is the base module, e.g. "mlx_lm.models.qwen3". The
# generated file subclasses the base Model and swaps decoder Linears for fused
# QuantizedLinear layers.
MODEL_TEMPLATE = '''"""SLQ packed checkpoint architecture (auto-generated by slq-mlx).

The decoder Linear layers are replaced by MLX's fused ``QuantizedLinear``, so
the packed integer grid is dequantized inside the matmul kernel and the model
stays small in memory as well as on disk.

Load with::

    from mlx_lm import load
    model, tokenizer = load(path, trust_remote_code=True)

``trust_remote_code`` is required because mlx-lm imports this file to build
the architecture. Only load checkpoints you trust.
"""

import json
from dataclasses import dataclass

import mlx.nn as nn

from {model_module} import Model as _BaseModel
from {model_module} import ModelArgs as _BaseModelArgs


@dataclass
class ModelArgs(_BaseModelArgs):
    """Base args plus the per-layer SLQ bitwidth map."""

    slq_bits: dict = None

    @classmethod
    def from_dict(cls, params):
        params = dict(params)
        raw = params.get("slq_bits")
        if isinstance(raw, str):
            params["slq_bits"] = json.loads(raw)
        return super().from_dict(params)


class Model(_BaseModel):
    """Base model with decoder Linears swapped for fused QuantizedLinear layers."""

    def __init__(self, args):
        super().__init__(args)
        bits_map = getattr(args, "slq_bits", None) or {{}}
        for i, block in enumerate(self.layers):
            for name, layer in list(block.named_modules()):
                if not isinstance(layer, nn.Linear):
                    continue
                key = f"layers.{{i}}.{{name}}"
                _set_submodule(block, name, _quantized(layer, bits_map.get(key, 8)))


def _set_submodule(module, dotted, child):
    """Set ``module.<dotted>`` to ``child``."""
    parts = dotted.split(".")
    parent = module
    for part in parts[:-1]:
        parent = parent[int(part)] if part.isdigit() else getattr(parent, part)
    setattr(parent, parts[-1], child)


def _quantized(linear, bits):
    """QuantizedLinear shaped like ``linear``; weights arrive via load_weights."""
    q = nn.QuantizedLinear(
        linear.weight.shape[1],
        linear.weight.shape[0],
        bias=hasattr(linear, "bias") and linear.bias is not None,
        group_size={group_size},
        bits=bits,
        mode="affine",
    )
    q.bits = bits
    return q
'''


def model_module_text(base_module: str, group_size: int) -> str:
    return MODEL_TEMPLATE.format(model_module=base_module, group_size=group_size)


def base_model_module(model_type: str) -> str:
    """Map a model_type onto its mlx-lm module path."""
    from mlx_lm.utils import MODEL_REMAPPING

    return f"mlx_lm.models.{MODEL_REMAPPING.get(model_type, model_type)}"


