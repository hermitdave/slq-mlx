def parse_config(path) -> dict:
    """Parse a '# key: value' header plus 'layer: bits' body."""
    config, _meta = {}, {}
    for line in Path(path).read_text().splitlines():
        line = line.strip()
        if line.startswith("#"):
            k, s, v = line[1:].partition(":")
            if s:
                _meta[k.strip().lower().replace(" ", "_")] = v.strip()
        elif ":" in line:
            n, b = line.rsplit(":", 1)
            config[n.strip()] = int(b)
    return config


def _base_config(model_id: str, base) -> dict:
    """Read the base model's config.json, local path or HF repo."""
    local = Path(model_id) / "config.json"
    if local.exists():
        return json.loads(local.read_text())
    from huggingface_hub import snapshot_download

    path = snapshot_download(model_id, allow_patterns=["config.json"])
    return json.loads((Path(path) / "config.json").read_text())


def flatten(d, prefix=""):
    out = {}
    for k, v in d.items():
        key = f"{prefix}{k}"
        if isinstance(v, dict):
            out.update(flatten(v, key + "."))
        elif isinstance(v, list):
            for i, item in enumerate(v):
                if isinstance(item, dict):
                    out.update(flatten(item, f"{key}.{i}."))
                else:
                    out[f"{key}.{i}"] = item
        else:
            out[key] = v
    return out


def pack_checkpoint(
    model_id: str,
    layer_dir: str,
    config_path: str,
    output_dir: str,
    group_size: int = 128,
    keep_dtype: str = "float16",
    subdir_name: str = None,
) -> dict:
    """Write a packed mlx-lm checkpoint.

    Returns a summary dict with the achieved size and bitwidth.
    """
    if group_size not in SUPPORTED_GROUP_SIZES:
        raise ValueError(
            f"group_size {group_size} not supported by mx.quantize; "
            f"choose one of {SUPPORTED_GROUP_SIZES}"
        )

    config = parse_config(config_path)
    if not config:
        raise ValueError(f"No layer bitwidths parsed from {config_path}")

    store = WeightStore(layer_dir).load()

    from mlx_lm import load as load_mlx

    base, tokenizer = load_mlx(model_id)
    base_params = flatten(base.parameters())
    base_cfg = _base_config(model_id, base)

    out = Path(output_dir) / Path(model_id).name
    if subdir_name:
        out = out / subdir_name
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    weights = {}
    bitwidths = {}
    rounded = {}
    total_params = param_bits = 0

    for name, requested in sorted(config.items()):
        bits = effective_bits(requested)
        if bits != requested:
            rounded[name] = (requested, bits)
            logger.warning(f"{name}: {requested}-bit rounds up to {bits}-bit (mx.quantize)")

        qw, scales, zeros, gs = store.get_qparams(name, bits)
        d_row, d_col = qw.shape
        if gs != group_size:
            raise ValueError(
                f"{name}: store group_size {gs} != requested {group_size}"
            )

        # Pack the store's own integer grid straight into MLX's layout and
        # carry the store's scales/zeros through unchanged.
        #
        # ``mx.dequantize(w, S, B) == w*S + B`` exactly (verified), so this
        # reproduces the store's dequantized weight to float32 epsilon. The
        # obvious alternative -- dequantize then ``mx.quantize`` -- is *not*
        # lossless: mx.quantize recomputes each group's scale from the
        # dequantized range, which does not reproduce the GPTQ group scale,
        # and a group whose grid does not span the full [0, 2^bits) range
        # comes back stretched.
        key = f"model.{name}"
        weights[f"{key}.weight"] = mx.array(pack_weight(np.asarray(qw), bits))
        weights[f"{key}.scales"] = mx.array(np.asarray(scales, dtype=np.float32))
        weights[f"{key}.biases"] = mx.array(np.asarray(zeros, dtype=np.float32))
        bitwidths[name] = bits

        total_params += d_row * d_col
        param_bits += d_row * d_col * bits

    # Anything the search did not touch keeps its weight. float16 because
    # safetensors.mlx cannot serialise bfloat16 (no PEP 3118 buffer format).
    keep_dtype_mx = {"float16": mx.float16, "float32": mx.float32}[keep_dtype]
    kept = 0
    for k, v in base_params.items():
        if k not in weights:
            weights[k] = v.astype(keep_dtype_mx) if v.dtype == mx.bfloat16 else v
            kept += 1

    save_file(weights, str(out / "model.safetensors"))
    (out / "slq_model.py").write_text(
        model_module_text(base_model_module(base_cfg["model_type"]), group_size)
    )

    base_cfg["model_file"] = "slq_model.py"
    base_cfg["slq_bits"] = json.dumps(bitwidths)
    base_cfg["quantization_config"] = {
        "quant_method": "slq",
        "bits": round(param_bits / total_params, 4),
        "group_size": group_size,
        "format": "mlx-packed-affine",
    }
    (out / "config.json").write_text(json.dumps(base_cfg, indent=2))
    tokenizer.save_pretrained(str(out))

    size = (out / "model.safetensors").stat().st_size
    summary = {
        "path": str(out),
        "layers": len(bitwidths),
        "kept_tensors": kept,
        "quantized_params": total_params,
        "average_bitwidth": param_bits / total_params,
        "safetensors_bytes": size,
        "rounded_up": rounded,
    }
    return summary
